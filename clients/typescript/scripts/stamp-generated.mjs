// Prepends a header to the generated OpenAPI types so the file says where it comes from.
import { readFileSync, writeFileSync } from 'node:fs'

const file = new URL('../src/generated/openapi.ts', import.meta.url)
const header = '/* eslint-disable */\n// Generated by `npm run gen` from openapi.json (openapi-typescript). Do not edit.\n'
const body = readFileSync(file, 'utf8').replace(/^\/\* eslint-disable \*\/\n\/\/ Generated by[^\n]*\n/, '')
writeFileSync(file, header + body)
