class Tx:
    """Texts in one language."""

    def __init__(self, lang: str) -> None:
        """Pick a language (English for anything else).

        Args:
            lang: ``en`` or ``it``.
        """
        self.lang = lang if lang in LANGS else "en"
        self._i = LANGS.index(self.lang)

    def __call__(self, key: str, **params: Any) -> str:
        """A text with its parameters filled in.

        Returns:
            The text (``KeyError`` for an unknown key).
        """
        text = T[key][self._i]
        return text.format(**params) if params else text

    def params(self, params: dict[str, Any]) -> dict[str, Any]:
        """Parameters of a reason or an obligation, lists of ids turned into words.

        Returns:
            The parameters.
        """
        out = {}
        for k, v in params.items():
            if k in _ENUMS and isinstance(v, list):
                out[k] = self.join(self(f"{_ENUMS[k]}.{x}") for x in v)
            elif isinstance(v, list):
                out[k] = self.join(str(x) for x in v)
            else:
                out[k] = v
        return out

    def join(self, items: Iterable[str]) -> str:
        """Items as one phrase.

        Returns:
            Comma separated items.
        """
        return ", ".join(x for x in items if x)

    def date(self, iso: str | None) -> str:
        """A date as the language writes it.

        Returns:
            ``2026-11-16`` in English, ``16/11/2026`` in Italian, or ``-``.
        """
        if not iso:
            return "-"
        try:
            d = datetime.fromisoformat(iso)
        except ValueError:
            return iso[:10]
        return d.strftime("%d/%m/%Y") if self.lang == "it" else d.strftime("%Y-%m-%d")

    def datetime(self, iso: str | None) -> str:
        """A date and time (UTC).

        Returns:
            The text.
        """
        if not iso:
            return "-"
        try:
            d = datetime.fromisoformat(iso)
        except ValueError:
            return iso[:16]
        fmt = "%d/%m/%Y %H:%M" if self.lang == "it" else "%Y-%m-%d %H:%M"
        return f"{d.strftime(fmt)} UTC"

    def action(self, action: str) -> str:
        """An audit action in words.

        Returns:
            The words, or the action itself.
        """
        words = _ACTION_WORDS.get(action)
        return words[self._i] if words else action

    def sources(self) -> dict[str, str]:
        """Every source's label.

        Returns:
            key to label.
        """
        return {k: v[self._i] for k, v in SOURCES.items()}
